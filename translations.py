def get_text(lang_code: str, key: str, **kwargs) -> str:
    lang = lang_code if lang_code in TRANSLATIONS else "en"
    val = TRANSLATIONS.get(lang, {}).get(key, TRANSLATIONS["en"].get(key, key))
    if kwargs:
        try:
            return val.format(**kwargs)
        except Exception:
            return val
    return val
